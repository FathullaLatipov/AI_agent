"""
Реестр инструментов агента.

Единая точка входа для вызова инструментов. Агент НЕ знает про конкретные
функции (get_orders и т.д.) — он лишь говорит: "вызови инструмент с именем NAME
и аргументами ARGS". Здесь имя сопоставляется с реальной функцией и с
Pydantic-моделью её аргументов.
"""

from pydantic import ValidationError
from tools.orders import get_orders, GetOrdersArgs

# Карта инструментов: имя -> (функция, модель аргументов).
# Имя, код и контракт аргументов живут одной записью: добавляя новый инструмент,
# ты в одном месте регистрируешь и функцию, и её валидацию — не забудешь.
TOOLS = {
    "get_orders": (get_orders, GetOrdersArgs),
}


def execute_tool(name: str, raw_args: dict) -> str:
    """
    Безопасно выполнить инструмент по имени.

    ВСЕГДА возвращает строку — и при успехе, и при любой ошибке; наружу
    исключения не пробрасываются. Почему так: результат уходит модели как
    содержимое роли "tool". Если вместо результата придёт текст ошибки — модель
    прочитает его и исправится на следующем шаге цикла. А если бросить
    исключение — весь агент упадёт.
    """

    # 1) Инструмента не существует.
    #    LLM может выдумать имя, которого нет. Не падаем — сообщаем модели,
    #    какие инструменты доступны, чтобы она выбрала правильный.
    if name not in TOOLS:
        return f"ERROR: инструмент '{name}' не существует. Доступные: {list(TOOLS)}"

    func, args_model = TOOLS[name]

    # 2) Валидация аргументов.
    #    raw_args сгенерированы нейросетью => это недоверенный ввод.
    #    Pydantic ловит мусор (не тот тип, выход за границы ge/le, пропущенное
    #    обязательное поле) ДО вызова функции.
    try:
        args = args_model(**raw_args)
    except ValidationError as e:
        return f"ERROR: аргументы не прошли валидацию для '{name}': {e}"

    # 3) Выполнение уже проверенными аргументами.
    #    Оборачиваем в try, потому что сама функция может упасть в рантайме
    #    (нет данных, ошибка БД и т.п.) — это тоже должно вернуться текстом,
    #    а не ронять агента.
    try:
        return func(**args.model_dump())
    except Exception as e:
        return f"ERROR: инструмент '{name}' упал при выполнении: {e}"
